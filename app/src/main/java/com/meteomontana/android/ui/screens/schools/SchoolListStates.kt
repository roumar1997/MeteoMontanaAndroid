// Estados vacíos y de error de la lista de Escuelas.

/** «No hay nada con estos filtros» + botón para quitarlos (escuelas y vías/bloques usan el mismo). */
@Composable
internal fun EmptyResults(onClear: () -> Unit) {
    Column(
        Modifier.fillMaxWidth().padding(Spacing.xl),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Text(
            stringResource(R.string.schools_empty),
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
        Spacer(Modifier.height(Spacing.md))
        OutlinedCumbreButton(text = stringResource(R.string.schools_clear_filters), onClick = onClear)
    }
}

@Composable
internal fun ErrorRow(message: String, onRetry: () -> Unit) {
    Column(
        Modifier.fillMaxWidth().padding(Spacing.xxl),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Text(
            stringResource(R.string.school_list_screen_v2_error_1_s, message),
            style = MaterialTheme.typography.bodyLarge,
            color = MaterialTheme.colorScheme.error
        )
        Spacer(Modifier.height(Spacing.md))
        OutlinedCumbreButton(text = stringResource(R.string.common_retry), onClick = onRetry)
    }
}
